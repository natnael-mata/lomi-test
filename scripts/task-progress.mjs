#!/usr/bin/env node
/**
 * Rewrites the progress index in TASK.md, and stamps each phase heading with its
 * state.
 *
 * Generated rather than hand-kept, because a hand-kept index is wrong within a
 * day and a wrong index is worse than none — it is the thing someone glances at
 * instead of counting. Run it after ticking boxes; CI checks it is current.
 *
 *   node scripts/task-progress.mjs          # rewrite in place
 *   node scripts/task-progress.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const TASK_MD = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'TASK.md');
const START = '<!-- progress:start -->';
const END = '<!-- progress:end -->';

/** A phase heading, with its own tasks and the state of each. */
function readPhases(lines) {
  const phases = [];
  let current = null;
  for (const line of lines) {
    const heading = /^## (Phase \d+[^\n]*)$/.exec(line);
    if (heading) {
      // Strip any previously stamped suffix so re-running is idempotent.
      const title = heading[1].replace(/\s+—\s+(✅ complete|\d+ left|blocked).*$/, '').trim();
      current = { title, done: 0, todo: 0, blocked: 0 };
      phases.push(current);
      continue;
    }
    if (!current) continue;
    if (/^- \[x\] \*\*T-/.test(line)) current.done++;
    else if (/^- \[ \] \*\*T-/.test(line)) current.todo++;
    else if (/^\s*> blocked:/.test(line)) current.blocked++;
  }
  return phases;
}

const state = (p) => {
  if (p.todo === 0) return '✅ complete';
  // A phase whose every remaining task is blocked is not "in progress" — saying
  // so hides that nobody can move it.
  if (p.blocked >= p.todo) return `blocked · ${p.todo} left`;
  return `${p.todo} left`;
};

function table(phases) {
  const rows = phases.map((p) => {
    const total = p.done + p.todo;
    const pct = total === 0 ? 0 : Math.round((p.done / total) * 100);
    return `| ${p.title} | ${p.done}/${total} | ${pct}% | ${state(p)} |`;
  });
  const done = phases.reduce((n, p) => n + p.done, 0);
  const total = phases.reduce((n, p) => n + p.done + p.todo, 0);
  return [
    START,
    '',
    `**${done} of ${total} tasks done.** Generated by \`node scripts/task-progress.mjs\` —`,
    'do not edit by hand.',
    '',
    '| Phase | Done | Pct | State |',
    '| ----- | ---- | --- | ----- |',
    ...rows,
    '',
    END,
  ].join('\n');
}

const source = readFileSync(TASK_MD, 'utf8');
const lines = source.split('\n');
const phases = readPhases(lines);

// Stamp each heading with its state.
let out = lines
  .map((line) => {
    const heading = /^## (Phase \d+[^\n]*)$/.exec(line);
    if (!heading) return line;
    const title = heading[1].replace(/\s+—\s+(✅ complete|\d+ left|blocked).*$/, '').trim();
    const phase = phases.find((p) => p.title === title);
    return phase ? `## ${title} — ${state(phase)}` : line;
  })
  .join('\n');

const block = table(phases);
if (out.includes(START)) {
  out = out.replace(new RegExp(`${START}[\\s\\S]*?${END}`), block);
} else {
  // First run: put it directly under the file's opening paragraph.
  const anchor = out.indexOf('\n---\n');
  out = `${out.slice(0, anchor)}\n\n${block}\n${out.slice(anchor)}`;
}

/**
 * Prettier pads markdown table cells to align them AND widens the `| --- |`
 * separator row to match, so a byte comparison reports "stale" on every run
 * after formatting. Only the content matters here, so runs of spaces and of
 * dashes are both collapsed before comparing.
 */
const normalise = (text) =>
  text
    .split('\n')
    .map((l) => l.replace(/\s+/g, ' ').replace(/-{2,}/g, '--').trimEnd())
    .join('\n');

if (process.argv.includes('--check')) {
  if (normalise(out) !== normalise(source)) {
    console.error('TASK.md progress index is stale — run: node scripts/task-progress.mjs');
    process.exit(1);
  }
  console.log('TASK.md progress index is current.');
} else {
  writeFileSync(TASK_MD, out);
  console.log(`progress index updated — ${phases.length} phases`);
}
